// Autonomous loop: new day + auto-forge on + an unforged older entry → forge it
(function autoLoop() {
  if (!S.autoForge || (!S.orKey && !S.nimKey)) return;
  const t = today();
  const pending = [...S.journal].reverse().find((j) => j.day !== t && !j.forged && j.text);
  if (!pending) return;
  pending.forged = -1;
  $('journalText').value = pending.text;
  editId = pending.id;
  forgeFromJournal(true);
})();
