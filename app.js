// ---- Journal → autonomous quest forging ----
function parseForge(text) {
  const out = [];
  for (const line of text.split('\n')) {
    const m = line.trim().match(/^[-*•]\s*(.+)$/);
    if (!m) continue;
    const parts = m[1].split('::').map((s) => s.trim());
    const tm = parts[0].match(/^(.+?)(?:\s*\[(side|minor|major|epic)\])?\s*$/i);
    if (!tm) continue;
    const q = { title: tm[1].slice(0, 120), rank: (tm[2] || 'minor').toLowerCase(), desc: '', steps: [], attrs: {}, coins: 0 };
    if (parts[1]) q.desc = parts[1].slice(0, 200);
    if (parts[2]) q.steps = parts[2].split(';').map((s) => s.trim().slice(0, 120)).filter(Boolean).slice(0, 5);
    if (parts[3]) {
      for (const a of parts[3].split(/[;,]/)) {
        const am = a.trim().match(/^([a-z]+)\s+(\d+)$/i);
        if (am) q.attrs[am[1].toLowerCase()] = Math.min(5, parseInt(am[2], 10));
      }
    }
    if (parts[4]) { const cm = parts[4].match(/(\d+)/); if (cm) q.coins = Math.min(50, parseInt(cm[1], 10)); }
    if (!q.coins) q.coins = COINS[q.rank];
    out.push(q);
  }
  return out.slice(0, 8);
}

let editId = null;
function renderJournal() {
  const list = $('journalList');
  list.innerHTML = S.journal.length ? '' : '<li>No entries yet. Write your first one above.</li>';
  for (const j of [...S.journal].reverse().slice(0, 7)) {
    const li = document.createElement('li');
    const strong = document.createElement('strong');
    strong.textContent = j.day + (j.forged > 0 ? ` · forged ${j.forged} quests` : '') + (editId === j.id ? ' · editing' : '');
    li.appendChild(strong);
    li.appendChild(document.createTextNode(' — ' + (j.text.length > 140 ? j.text.slice(0, 140) + '…' : j.text)));
    li.style.cursor = 'pointer';
    li.title = 'Tap to read / edit';
    li.onclick = () => {
      if (editId === j.id) { editId = null; $('journalText').value = ''; $('forgeBtn').textContent = 'Forge my quests'; }
      else { editId = j.id; $('journalText').value = j.text; $('forgeBtn').textContent = 'Save + re-forge'; $('journalText').focus(); }
      renderJournal();
    };
    list.appendChild(li);
  }
  $('autoForge').checked = !!S.autoForge;
}

async function forgeFromJournal(silent) {
  const text = $('journalText').value.trim();
  if (!text) { if (!silent) toast('Write something in your journal first'); return; }
  if (!S.orKey && !S.nimKey) { if (!silent) toast('Add your OpenRouter key in Settings first'); return; }
  if (!silent) toast('Reading your journal…');
  const msgs = [
    { role: 'system', content: FORGE_SYS },
    { role: 'user', content: `Player: Lv ${level()} ${titleFor(level())}, top attributes: ${topAttrs().map(([k, v]) => k + ' ' + v).join(', ') || 'none'}.\nJournal:\n${text.slice(0, 2000)}` },
  ];
  let quests = [];
  if (S.orKey) {
    try {
      quests = parseForge(await callChat('https://openrouter.ai/api/v1/chat/completions', S.orKey, S.orModel, msgs));
    } catch (err) { /* fall through to NIM */ }
  }
  if (!quests.length && S.nimKey) {
    try {
      quests = parseForge(await callChat('https://integrate.api.nvidia.com/v1/chat/completions', S.nimKey, S.nimModel, msgs));
    } catch (err) { /* fall through */ }
  }
  if (!quests.length) { if (!silent) toast('The forge is cold — providers failed. Check keys.'); return; }
  if (editId) {
    const j = S.journal.find((x) => x.id === editId);
    if (j) { j.text = text.slice(0, 2000); j.forged = quests.length; }
    editId = null;
    $('forgeBtn').textContent = 'Forge my quests';
  } else {
    S.journal.push({ id: Date.now() + '', day: today(), text: text.slice(0, 2000), forged: quests.length });
  }
  quests.forEach(addQuestSilent);
  touchDay();
  save(); render(); renderJournal();
  $('journalText').value = '';
  toast(`Forged ${quests.length} quests — tap any quest for steps + rewards`);
}

