/* Forge — journal → AI analysis → quests with AI-generated rewards.
   Core loop from the video: journal, get analyzed, get a quest.
   Rewards per quest: XP + attribute points (focus/discipline/…) + coins,
   all generated by the AI based on the quest itself. State in localStorage. */
const XP = { side: 10, minor: 25, major: 50, epic: 100 };
const COINS = { side: 5, minor: 10, major: 25, epic: 50 };
const TITLES = [[1, 'Novice'], [3, 'Apprentice'], [5, 'Knight'], [8, 'Veteran'], [12, 'Champion'], [16, 'Legend']];
const COACH_SYS = `You are the Forge Quest-Master, a terse RPG mentor. Rules:
- Give quests as short "- title" lines when the user asks for tasks or a plan.
- Keep replies under 120 words. No fluff, no purple prose.
- Celebrate completions briefly. Push back on excuses, kindly but firmly.`;
const FORGE_SYS = `You turn a personal journal entry into RPG quests. Output ONLY quest blocks, one per line, exactly this shape:
- title [rank] :: one-line description :: step 1; step 2; step 3 :: attr points; attr points :: Nc
Rules: rank is side, minor, major or epic (mostly minor/side). 3-6 quests. Steps are short concrete instructions (2-4). Attributes chosen from focus, discipline, creativity, energy, courage, wisdom — 1-5 points each, matching what the quest builds. N is coins 5-50. No other text.`;

const store = {
  load() { try { return JSON.parse(localStorage.getItem('forge') || '{}'); } catch { return {}; } },
  save(s) { localStorage.setItem('forge', JSON.stringify(s)); },
};
let S = Object.assign({ xp: 0, coins: 0, attrs: {}, quests: [], streak: 0, lastDay: null, journal: [], autoForge: false, orKey: '', orModel: 'meta-llama/llama-3.3-70b-instruct:free', nimKey: '', nimModel: 'meta/llama-3.3-70b-instruct' }, store.load());
const save = () => store.save(S);
const today = () => new Date().toISOString().slice(0, 10);
const $ = (id) => document.getElementById(id);
const esc = (s) => s;

function level() { return Math.floor(Math.sqrt(S.xp / 100)) + 1; }
function levelBase(l) { return 100 * (l - 1) * (l - 1); }
function titleFor(l) { let t = TITLES[0][1]; for (const [lv, name] of TITLES) if (l >= lv) t = name; return t; }

function toast(msg) {
  const el = $('toast');
  el.textContent = msg; el.hidden = false;
  clearTimeout(el._t);
  el._t = setTimeout(() => { el.hidden = true; }, 2800);
}

function topAttrs(n = 3) {
  return Object.entries(S.attrs).sort((a, b) => b[1] - a[1]).slice(0, n);
}

function render() {
  const l = level(), base = levelBase(l), next = levelBase(l + 1);
  $('charTitle').textContent = titleFor(l);
  $('levelBadge').textContent = 'Lv ' + l;
  $('xpText').textContent = S.xp + ' XP · ' + S.coins + ' coins';
  $('xpFill').style.width = Math.min(100, ((S.xp - base) / (next - base)) * 100) + '%';
  const open = S.quests.filter((q) => !q.done), done = S.quests.filter((q) => q.done);
  $('streakNum').textContent = S.streak;
  $('doneNum').textContent = done.length;
  $('openNum').textContent = open.length;
  const ta = topAttrs().map(([k, v]) => `${k} ${v}`).join(' · ') || 'No attributes yet — complete a quest';
  $('attrLine').textContent = ta;

  $('activeList').innerHTML = open.length ? '' : '<li class="empty">No active quests. Journal below and let the AI forge some — or add one manually.</li>';
  for (const q of open) $('activeList').appendChild(questNode(q, false));
  $('doneList').innerHTML = done.length ? '' : '<li class="empty">Nothing completed yet. Your legend starts with one quest.</li>';
  for (const q of [...done].reverse().slice(0, 20)) $('doneList').appendChild(questNode(q, true));
}

function rewardText(q) {
  const parts = [`+${XP[q.rank]} XP`, `+${COINS[q.rank]} coins`];
  for (const [k, v] of Object.entries(q.attrs || {})) parts.push(`+${v} ${k}`);
  return parts.join(' · ');
}

function questNode(q, isDone) {
  const li = document.createElement('li');
  li.className = 'quest' + (isDone ? ' is-done' : '');
  const head = document.createElement('div');
  head.className = 'quest-head';
  head.innerHTML = `<span class="rank">${q.rank}</span>`;
  const t = document.createElement('span');
  t.className = 'title'; t.textContent = q.title;
  head.appendChild(t);
  const xp = document.createElement('span');
  xp.className = 'xp'; xp.textContent = `+${XP[q.rank]} XP`;
  head.appendChild(xp);
  li.appendChild(head);
  if (q.desc || (q.steps && q.steps.length) || q.attrs) {
    const det = document.createElement('div');
    det.className = 'quest-detail';
    det.hidden = true;
    if (q.desc) { const d = document.createElement('p'); d.className = 'qdesc'; d.textContent = q.desc; det.appendChild(d); }
    if (q.steps && q.steps.length) {
      const ol = document.createElement('ol');
      ol.className = 'qsteps';
      q.steps.forEach((s) => { const sli = document.createElement('li'); sli.textContent = s; ol.appendChild(sli); });
      det.appendChild(ol);
    }
    const r = document.createElement('p');
    r.className = 'qrewards'; r.textContent = 'Rewards: ' + rewardText(q);
    det.appendChild(r);
    li.appendChild(det);
    head.style.cursor = 'pointer';
    head.onclick = () => { det.hidden = !det.hidden; };
  }
  if (!isDone) {
    const btn = document.createElement('button');
    btn.className = 'btn btn-gold btn-sm'; btn.textContent = 'Complete';
    btn.onclick = (e) => { e.stopPropagation(); completeQuest(q.id); };
    li.appendChild(btn);
  }
  return li;
}

function newQuest(o) {
  return { id: Date.now() + '' + Math.floor(Math.random() * 1e4), title: o.title, rank: o.rank || 'minor', desc: o.desc || '', steps: o.steps || [], attrs: o.attrs || {}, done: false, created: today() };
}
function addQuest(title, rank = 'minor') { S.quests.push(newQuest({ title, rank })); save(); render(); }
function addQuestSilent(o) { S.quests.push(newQuest(o)); }

function completeQuest(id) {
  const q = S.quests.find((x) => x.id === id);
  if (!q || q.done) return;
  const before = level();
  q.done = true; q.doneDay = today();
  S.xp += XP[q.rank];
  S.coins += COINS[q.rank];
  for (const [k, v] of Object.entries(q.attrs || {})) S.attrs[k] = (S.attrs[k] || 0) + v;
  touchDay();
  save(); render();
  const after = level();
  toast(after > before ? `LEVEL UP! Lv ${after} ${titleFor(after)} — ${rewardText(q)}` : `Quest complete — ${rewardText(q)}`);
}

function touchDay() {
  const t = today();
  if (S.lastDay === t) return;
  const y = new Date(Date.now() - 864e5).toISOString().slice(0, 10);
  S.streak = S.lastDay === y ? S.streak + 1 : 1;
  S.lastDay = t;
}

